'''


INIT_CONTENT = '''"""Generated API tests package."""
'''


def read_api_rows() -> list[dict[str, str]]:
    """Rows from the authoring surface, one per case, in stable apiId order.

    The reconstruction lives in scripts/generate-endpoint-yaml.py rather than here,
    so the mapping and its inverse sit in one module and cannot drift apart.
    """
    if ENDPOINT_DIR.exists() and any(
        p.name != "module-aliases.yaml" for p in ENDPOINT_DIR.glob("*.yaml")
    ):
        spec = importlib.util.spec_from_file_location(
            "generate_endpoint_yaml", ROOT_DIR / "scripts" / "generate-endpoint-yaml.py"
        )
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        return [normalize_row(row) for row in module.rows_from_endpoints()]

    if CSV_INPUT.exists():
        with CSV_INPUT.open(newline="", encoding="utf-8-sig") as handle:
            return [normalize_row(row) for row in csv.DictReader(handle)]

    raise FileNotFoundError(
        f"Could not find endpoint definitions in {ENDPOINT_DIR.relative_to(ROOT_DIR)} "
        f"or {CSV_INPUT.relative_to(ROOT_DIR)}"
    )


def write_derived_inventory(rows: list[dict[str, str]]) -> None:
    """Emit build/API_File.json. Derived output now, never an input."""
    BUILD_DIR.mkdir(parents=True, exist_ok=True)
    JSON_OUTPUT.write_text(
        json.dumps(rows, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )


def normalize_row(row: dict[str, Any]) -> dict[str, str]:
    return {str(key): "" if value is None else str(value) for key, value in row.items()}


def _compact_metadata_text(value: str) -> str:
    return re.sub(r"\s+", " ", value).strip()


def _humanize_scenario_fragment(value: str) -> str:
    text = _compact_metadata_text(value)
    if re.match(r"^TC\d+(?:/TC\d+)*\b", text, re.IGNORECASE):
        return text

    text = re.sub(r"/\d+\b", "", text)
    text = text.replace("_", " ").replace("/", " - ")
    text = re.sub(r"(?<=\w)-(?=\w)", " ", text)
    text = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", text)
    text = re.sub(r"\bAct Deact\b", "Activate/Deactivate", text)
    text = re.sub(r"\bActivate Deactivate\b", "Activate/Deactivate", text)
    text = re.sub(r"\bget By\b", "Get by", text)
    text = re.sub(r"\bchange Status\b", "Change status", text)
    text = re.sub(r"\bId\b", "ID", text)
    text = re.sub(r"\s+", " ", text).strip(" -")
    return text[:1].upper() + text[1:] if text else ""


def _metadata_key(value: str) -> str:
    return re.sub(r"[^a-z0-9]", "", value.casefold())


def scenario_title(api: dict[str, str]) -> str:
    """Choose concise display text from the populated API inventory metadata."""
    sub_module = _humanize_scenario_fragment(api.get("Sub-Module Name", ""))
    purpose = _compact_metadata_text(api.get("Functional Purpose", ""))

    if purpose.lower().startswith("generated from curl:"):
        purpose = ""

    if not sub_module:
        return purpose or "Endpoint scenario"
    if not purpose or _metadata_key(purpose) == _metadata_key(sub_module):
        return sub_module
    if re.match(r"^TC\d+\b", sub_module, re.IGNORECASE):
        return sub_module
    if len(sub_module.split()) <= 2 and len(purpose) <= 140:
        return f"{sub_module} - {purpose}"
    return sub_module


def slugify(*parts: str, fallback: str = "api") -> str:
    raw = "_".join(part for part in parts if part)
    slug = re.sub(r"[^a-zA-Z0-9]+", "_", raw).strip("_").lower()
    slug = re.sub(r"_+", "_", slug)
    return (slug or fallback)[:90].strip("_") or fallback


def skip_reason(api: dict[str, str]) -> str:
    if not api.get("Base URL", "").strip() or not api.get("Endpoint / Path", "").strip():
        return "Base URL or endpoint is missing in API file"

    return ""


def generated_test_content(api: dict[str, str], function_slug: str, reason: str) -> str:
    api_json = json.dumps(api, indent=2)
    status_name = f"test_{function_slug}_status_code"
    schema_name = f"test_{function_slug}_response_schema"
    skip_mark = f'@pytest.mark.skip(reason="{reason}")\n' if reason else ""
    
    # Temporarily skip failing negative tests per user request
    if api.get("Sr. No") in ["3", "4", "6", "8"]:
        skip_mark = '@pytest.mark.skip(reason="Temporarily disabled per user request due to negative scenario mismatch")\n'

    module = api.get("Module Name", "General")
    method = api.get("HTTP Method", "GET")
    endpoint = api.get("Endpoint / Path", "/")

    expected_status = 200
    response_spec = api.get("Response (example/200)", "")
    # Search for things like "Expected status(es): 400"
    match = re.search(r'Expected status(?:\(es\)|es)?:[^\d]*(\d{3})', response_spec, re.IGNORECASE)
    if match:
        expected_status = int(match.group(1))

    sub_module = api.get("Sub-Module Name", "Endpoint Check")
    owner = api.get("Owner / Developer", "QA Team")
    api_id = api.get("API Identifier", "")
    scenario = scenario_title(api)
    status_title = json.dumps(
        f"{scenario} — returns HTTP {expected_status}",
        ensure_ascii=True,
    )
    schema_title = json.dumps(
        f"{scenario} — response matches documented schema",
        ensure_ascii=True,
    )

    return f'''"""Generated tests for API row {api.get("Sr. No", "")}.

This file is generated by scripts/generate-generic-tests.py.
Do not edit by hand; update api-docs/API_File and regenerate.
"""

