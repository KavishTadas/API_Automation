    config = _RuntimeConfig(load_runtime_config())
    with (ROOT_DIR / "build" / "API_File.json").open(encoding="utf-8-sig") as handle:
        api_rows = json.load(handle)

    auth_row = next(
        row
        for row in api_rows
        if row.get("Module Name") == "Employee Auth API"
        and row.get("HTTP Method") == "POST"
        and row.get("Endpoint / Path") == "/auth/token"
        and re.search(
            r"Expected status\(es\):[^\n]*\b2\d\d\b",
            row.get("Response (example/200)", ""),
        )
    )
    response = perform_api_request(auth_row, config)
    assert response.is_success, (
        f"Employee Auth bootstrap returned {response.status_code}; "
        "response body withheld"
    )

    payload = response.json()
    token = None
    if isinstance(payload, dict):
        token = payload.get("token") or payload.get("access_token") or payload.get("authToken")
        if not token and isinstance(payload.get("data"), dict):
            token = payload["data"].get("token") or payload["data"].get("access_token") or payload["data"].get("authToken")
            
