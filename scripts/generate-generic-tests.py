def read_api_rows() -> list[dict[str, str]]:
    if JSON_INPUT.exists():
        with JSON_INPUT.open(encoding="utf-8-sig") as handle:
            rows = json.load(handle)
        return [normalize_row(row) for row in rows]

    if CSV_INPUT.exists():
        with CSV_INPUT.open(newline="", encoding="utf-8-sig") as handle:
            return [normalize_row(row) for row in csv.DictReader(handle)]

    raise FileNotFoundError(
        f"Could not find {JSON_INPUT.relative_to(ROOT_DIR)} or "
        f"{CSV_INPUT.relative_to(ROOT_DIR)}"
    )


def normalize_row(row: dict[str, Any]) -> dict[str, str]:
    return {str(key): "" if value is None else str(value) for key, value in row.items()}


def slugify(*parts: str, fallback: str = "api") -> str:
    raw = "_".join(part for part in parts if part)
    slug = re.sub(r"[^a-zA-Z0-9]+", "_", raw).strip("_").lower()
    slug = re.sub(r"_+", "_", slug)
    return (slug or fallback)[:90].strip("_") or fallback


def skip_reason(api: dict[str, str]) -> str:
    if not api.get("Base URL", "").strip() or not api.get("Endpoint / Path", "").strip():
        return "Base URL or endpoint is missing in API file"

    response_spec = api.get("Response (example/200)", "")
    if response_spec and "200" not in response_spec:
        return "API row documents a non-200 or negative scenario, not a valid request"

    return ""


def generated_test_content(api: dict[str, str], function_slug: str, reason: str) -> str:
    api_json = json.dumps(api, indent=2)
    status_name = f"test_{function_slug}_status_code"
    schema_name = f"test_{function_slug}_response_schema"
    skip_mark = f'pytestmark = pytest.mark.skip(reason="{reason}")\n\n' if reason else ""
    module = api.get("Module Name", "General")
    method = api.get("HTTP Method", "GET")
    endpoint = api.get("Endpoint / Path", "/")

    return f'''"""Generated tests for API row {api.get("Sr. No", "")}.

This file is generated by scripts/generate-generic-tests.py.
Do not edit by hand; update api-docs/API_File and regenerate.
"""

from __future__ import annotations

import json

import allure
import pytest

from ._api_test_helpers import (
    assert_response_matches_schema,
    perform_api_request,
    skip_if_no_response_schema,
)


API = json.loads(r"""{api_json}""")

@allure.epic("{module}")
@allure.feature("{module} APIs")
@allure.story("{method} {endpoint}")
{skip_mark}def {status_name}(api_runtime_config: dict[str, str]) -> None:
    response = perform_api_request(API, api_runtime_config)
    assert response.status_code == 200


@allure.epic("{module}")
@allure.feature("{module} APIs")
@allure.story("{method} {endpoint}")
def {schema_name}(api_runtime_config: dict[str, str]) -> None:
    skip_if_no_response_schema(API)
    response = perform_api_request(API, api_runtime_config)
    assert response.status_code == 200
    assert_response_matches_schema(response, API)
'''


def clear_previous_generated_tests() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    failed_paths: list[Path] = []

    for path in OUTPUT_DIR.glob("test_*.py"):
        try:
            path.unlink()
        except PermissionError:
            failed_paths.append(path)

    if failed_paths:
        paths = ", ".join(str(path.relative_to(ROOT_DIR)) for path in failed_paths)
        raise RuntimeError(f"Could not remove stale generated test file(s): {paths}")


def write_generated_tests(rows: list[dict[str, str]]) -> list[Path]:
    clear_previous_generated_tests()
    (OUTPUT_DIR / "__init__.py").write_text(INIT_CONTENT, encoding="utf-8")
    (OUTPUT_DIR / "conftest.py").write_text(CONFTEST_CONTENT, encoding="utf-8")
    (OUTPUT_DIR / "_api_test_helpers.py").write_text(HELPER_CONTENT, encoding="utf-8")

    written: list[Path] = []
    for index, api in enumerate(rows, start=1):
        module = api.get("Module Name", "")
        endpoint = api.get("Endpoint / Path", "")
        method = api.get("HTTP Method", "")
        function_slug = slugify(module, endpoint, fallback=f"api_{index}")
        file_slug = slugify(method, module, endpoint, fallback=f"api_{index}")
        file_path = OUTPUT_DIR / f"test_{index:03d}_{file_slug}.py"
        file_path.write_text(
            generated_test_content(api, function_slug, skip_reason(api)),
            encoding="utf-8",
        )
        written.append(file_path)

    return written


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate pytest API tests from api-docs/API_File.json or CSV."
    )
    parser.add_argument(
        "--list-only",
        action="store_true",
        help="Read API file and print the number of rows without writing tests.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    rows = read_api_rows()

    if args.list_only:
        print(f"Loaded {len(rows)} API row(s).")
        return

    written = write_generated_tests(rows)
    print(f"Generated {len(written)} pytest file(s) in {OUTPUT_DIR.relative_to(ROOT_DIR)}.")
    print("Shared helpers:")
    print(f"  {(OUTPUT_DIR / '_api_test_helpers.py').relative_to(ROOT_DIR)}")
    print(f"  {(OUTPUT_DIR / 'conftest.py').relative_to(ROOT_DIR)}")


if __name__ == "__main__":
    main()
