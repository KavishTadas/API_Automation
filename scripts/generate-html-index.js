function renderNewmanSection(results) {
  const rows = results.map((r) => {
    const colPassed = numberValue(r.Passed);
    const colFailed = numberValue(r.Failed);
    const colStatus = colFailed === 0 ? 'PASS' : 'FAIL';
    const reportFile = r.reportFile
      ? `<a href="${escapeHtml(path.basename(r.reportFile))}">View Report</a>`
      : '<span class="muted">-</span>';

    return `
      <tr>
        <td>${escapeHtml(r.Collection)}</td>
        <td class="center">${escapeHtml(r.Requests)}</td>
        <td class="center" style="color:#1D9E75;font-weight:500">
          ${escapeHtml(colPassed)}
        </td>
        <td class="center" style="color:${colFailed > 0 ? '#D85A30' : '#999'};
                   font-weight:500">
          ${escapeHtml(colFailed)}
        </td>
        <td class="center">${(numberValue(r['Duration(ms)']) / 1000).toFixed(1)}s</td>
        <td class="center">${statusBadge(colStatus)}</td>
        <td class="center">${reportFile}</td>
      </tr>`;
  }).join('');

  return `
    <div class="section">
      <h2>Newman Collection Results</h2>
      ${results.length === 0
        ? '<p>No Newman collection summary was provided for this report run.</p>'
        : ''}
      <div class="table-wrap">
        <table>
          <thead>
            <tr>
              <th>Collection</th>
              <th class="center">Requests</th>
              <th class="center">Passed</th>
              <th class="center">Failed</th>
              <th class="center">Duration</th>
              <th class="center">Status</th>
              <th class="center">Full Report</th>
            </tr>
          </thead>
          <tbody>${rows || emptyRow(7, 'No Newman results found')}</tbody>
        </table>
      </div>
    </div>`;
}

function renderAutoGeneratedSection(cases, summary) {
  const rows = cases.map((testCase) => `
    <tr>
      <td>${escapeHtml(testCase.apiName)}</td>
      <td>${escapeHtml(testCase.testCase)}</td>
      <td>${statusBadge(testCase.status)}</td>
      <td>${escapeHtml(testCase.durationMs ? `${testCase.durationMs}ms` : '')}</td>
      <td>${escapeHtml(testCase.source)}</td>
      <td>${escapeHtml(testCase.details)}</td>
    </tr>`).join('');

  return `
    <div class="section">
      <h2>Auto-generated Test Cases</h2>
      <p>
        Total: ${summary.total} &nbsp;|&nbsp;
        Passed: ${summary.passed} &nbsp;|&nbsp;
        Failed: ${summary.failed} &nbsp;|&nbsp;
        Skipped: ${summary.skipped}
      </p>
      <div class="table-wrap">
        <table>
          <thead>
            <tr>
              <th>API Name</th>
              <th>Test Case</th>
              <th>Status</th>
              <th>Duration</th>
              <th>Source</th>
              <th>Details</th>
            </tr>
          </thead>
          <tbody>${rows || emptyRow(6, 'No auto-generated pytest results found')}</tbody>
        </table>
      </div>
    </div>`;
}

function readAutoGeneratedTestResults() {
  const metadataByName = readGeneratedTestMetadata();
  const allureCases = readAllureResults(metadataByName);

  if (allureCases.length > 0) {
    return allureCases;
  }

  return readJUnitResults(metadataByName);
}

function readGeneratedTestMetadata() {
  const metadata = {};

  if (!fs.existsSync(GENERATED_TESTS_DIR)) {
    return metadata;
  }

  listFiles(GENERATED_TESTS_DIR)
    .filter((filePath) => /^test_.*\.py$/.test(path.basename(filePath)))
    .forEach((filePath) => {
      const content = fs.readFileSync(filePath, 'utf8');
      const apiMatch = content.match(/API\s*=\s*json\.loads\(r"""([\s\S]*?)"""\)/);

      if (!apiMatch) {
        return;
      }

      let api;
      try {
        api = JSON.parse(apiMatch[1]);
      } catch (error) {
        return;
      }

      const functions = [...content.matchAll(/def\s+(test_[A-Za-z0-9_]+)\s*\(/g)]
        .map((match) => match[1]);

      functions.forEach((functionName) => {
        const item = {
          apiName: makeApiName(api),
          testCase: makeGeneratedTestCaseName(functionName, api),
          endpoint: api['Endpoint / Path'] || '',
          moduleName: api['Module Name'] || '',
          sourceFile: relativePath(filePath)
        };
        const fileBase = path.basename(filePath, '.py');
        metadata[functionName] = metadata[functionName] || item;
        metadata[`${fileBase}#${functionName}`] = item;
        metadata[`build.auto_generated.${fileBase}#${functionName}`] = item;
      });
    });

  return metadata;
}

function makeApiName(api) {
  return [
    api['Module Name'],
    api['HTTP Method'],
    api['Endpoint / Path']
  ].filter(Boolean).join(' - ');
}

function makeGeneratedTestCaseName(functionName, api) {
  const subModule = api['Sub-Module Name'] || api['Functional Purpose'] || functionName;

  if (functionName.endsWith('_status_code')) {
    return `${subModule} - HTTP 200 status`;
  }

  if (functionName.endsWith('_response_schema')) {
    return `${subModule} - response schema`;
  }

  return subModule;
}

function readAllureResults(metadataByName) {
  const preferredDirExists = fs.existsSync(GENERATED_ALLURE_DIR);
  const searchDir = preferredDirExists ? GENERATED_ALLURE_DIR : ALLURE_RESULTS_DIR;

  if (!fs.existsSync(searchDir)) {
    return [];
  }

  return listFiles(searchDir)
    .filter((filePath) => filePath.endsWith('-result.json'))
    .map((filePath) => parseAllureResult(filePath, metadataByName, preferredDirExists))
    .filter(Boolean)
    .sort(sortCases);
}

function parseAllureResult(filePath, metadataByName, includeAll) {
  let result;

  try {
    result = JSON.parse(stripBom(fs.readFileSync(filePath, 'utf8')));
  } catch (error) {
    return null;
  }

  const resultKey = makeResultLookupKey(result.fullName || '', result.name || '');
  const functionName = extractFunctionName(result.fullName || result.name || '');
  const metadata = metadataByName[resultKey] || metadataByName[functionName];
  const looksGenerated =
    includeAll ||
    Boolean(metadata) ||
    /auto_generated/.test(result.fullName || '') ||
    /build[/.\\]auto_generated/.test(filePath);

  if (!looksGenerated) {
    return null;
  }

  return {
    apiName: metadata?.apiName || labelValue(result, 'suite') || 'Auto-generated API',
    testCase: metadata?.testCase || result.name || functionName,
    status: normalizeStatus(result.status),
    durationMs: result.start && result.stop ? result.stop - result.start : 0,
    source: 'Allure JSON',
    details: result.statusDetails?.message || '',
    sortKey: `${metadata?.apiName || ''}${result.name || ''}`
  };
}

function readJUnitResults(metadataByName) {
  if (!fs.existsSync(REPORTS_DIR)) {
    return [];
  }

  return listFiles(REPORTS_DIR)
    .filter((filePath) => filePath.endsWith('.xml'))
    .flatMap((filePath) => parseJUnitFile(filePath, metadataByName))
    .sort(sortCases);
}

function parseJUnitFile(filePath, metadataByName) {
  const xml = fs.readFileSync(filePath, 'utf8');
  const cases = [];
  const regex = /<testcase\b([^>]*?)(?:\/>|>([\s\S]*?)<\/testcase>)/g;
  let match;

  while ((match = regex.exec(xml)) !== null) {
    const attrs = parseXmlAttrs(match[1] || '');
    const body = match[2] || '';
    const resultKey = makeResultLookupKey(attrs.classname || '', attrs.name || '');
    const functionName = extractFunctionName(attrs.name || '');
    const metadata = metadataByName[resultKey] || metadataByName[functionName];
    const generated =
      Boolean(metadata) ||
      /auto_generated/.test(attrs.classname || '') ||
      /auto_generated/.test(attrs.file || '');

    if (!generated) {
      continue;
    }

    const failed = /<(failure|error)\b/.test(body);
    const skipped = /<skipped\b/.test(body);
    cases.push({
      apiName: metadata?.apiName || attrs.classname || 'Auto-generated API',
      testCase: metadata?.testCase || attrs.name || functionName,
      status: failed ? 'FAIL' : skipped ? 'SKIP' : 'PASS',
      durationMs: attrs.time ? Math.round(Number(attrs.time) * 1000) : 0,
      source: 'JUnit XML',
      details: stripTags(body).slice(0, 300),
      sortKey: `${metadata?.apiName || ''}${attrs.name || ''}`
    });
  }

  return cases;
}

function summarizeAutoCases(cases) {
  return cases.reduce((summary, testCase) => {
    summary.total += 1;
    if (testCase.status === 'PASS') {
      summary.passed += 1;
    } else if (testCase.status === 'SKIP') {
      summary.skipped += 1;
    } else {
      summary.failed += 1;
    }
    return summary;
  }, { total: 0, passed: 0, failed: 0, skipped: 0 });
}

function listFiles(dirPath) {
  if (!fs.existsSync(dirPath)) {
    return [];
  }

  return fs.readdirSync(dirPath, { withFileTypes: true }).flatMap((entry) => {
    const fullPath = path.join(dirPath, entry.name);
    return entry.isDirectory() ? listFiles(fullPath) : [fullPath];
  });
}

function extractFunctionName(value) {
  const text = String(value || '');
  if (text.includes('#')) {
    return text.split('#').pop();
  }
  return text.split('.').pop();
}

function makeResultLookupKey(fullName, name) {
  const full = String(fullName || '');
  const testName = extractFunctionName(name || full);

  if (full.includes('#')) {
    return full;
  }

  const moduleName = full.split('.').slice(-1)[0];
  return moduleName ? `${moduleName}#${testName}` : testName;
}

function normalizeStatus(status) {
  if (status === 'passed') {
    return 'PASS';
  }
  if (status === 'skipped') {
    return 'SKIP';
  }
  return 'FAIL';
}

function labelValue(result, name) {
  const label = (result.labels || []).find((item) => item.name === name);
  return label ? label.value : '';
}

function parseXmlAttrs(rawAttrs) {
  const attrs = {};
  const regex = /([A-Za-z_:][A-Za-z0-9_.:-]*)="([^"]*)"/g;
  let match;

  while ((match = regex.exec(rawAttrs)) !== null) {
    attrs[match[1]] = unescapeXml(match[2]);
  }

  return attrs;
}

function summaryCard(label, value, className = '', inlineColor = '') {
  const colorStyle = inlineColor ? ` style="color:${inlineColor}"` : '';
  const classAttr = className ? ` ${className}` : '';
  return `
    <div class="card">
      <div class="card-label">${escapeHtml(label)}</div>
      <div class="card-value${classAttr}"${colorStyle}>${escapeHtml(value)}</div>
    </div>`;
}

function statusBadge(status) {
  const normalized = String(status || '').toUpperCase();
  const color = normalized === 'PASS'
    ? '#1D9E75'
    : normalized === 'SKIP'
      ? '#8b8fa8'
      : '#D85A30';

  return `<span class="badge" style="background:${color}22;color:${color}">
    ${escapeHtml(normalized || 'UNKNOWN')}
  </span>`;
}

function emptyRow(colspan, message) {
  return `<tr><td colspan="${colspan}" class="center muted">${escapeHtml(message)}</td></tr>`;
}

function stripTags(value) {
  return unescapeXml(String(value || '').replace(/<[^>]+>/g, ' '))
    .replace(/\s+/g, ' ')
    .trim();
}

function escapeHtml(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function unescapeXml(value) {
  return String(value || '')
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&amp;/g, '&');
}

function numberValue(value) {
  const number = Number(value);
  return Number.isFinite(number) ? number : 0;
}

function relativePath(filePath) {
  return path.relative(ROOT_DIR, filePath).split(path.sep).join('/');
}

function sortCases(a, b) {
  return String(a.sortKey || '').localeCompare(String(b.sortKey || ''));
}

if (require.main === module) {
  generateIndex([]);
}

module.exports = {
  generateIndex,
  readAutoGeneratedTestResults
};
